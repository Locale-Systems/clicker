def build_manchester(bits: str, half_us: int, jitter: float, seed: int) -> list[int]:
    """Jittered Manchester frame (mirrors rf_device_manager's test helper)."""
    rng = random.Random(seed)
    halves: list[bool] = []
    for bit in bits:
        halves.extend((True, False) if bit == "1" else (False, True))
    timings: list[int] = []
    for level in halves:
        duration = round(half_us * (1 + rng.uniform(-jitter, jitter)))
        signed = duration if level else -duration
        if timings and (timings[-1] > 0) == (signed > 0):
            timings[-1] += signed
        else:
            timings.append(signed)
    if timings[-1] > 0:
        timings.append(-8000)
    else:
        timings[-1] = -8000
    return timings


def builtin_cases() -> list[tuple[str, list[int]]]:
    return [
        ("real: held fan button (CC1101)", HELD_CAPTURE),
        ("real: EV1527 event A", EV1527_A),
        ("real: EV1527 event B", EV1527_B),
        ("real: EV1527 event C", EV1527_C),
        ("real: Tasmota RfRaw B0", ra.parse_tasmota_rfraw(B0_RFRAW)),
        ("real: noise burst", NOISE),
        ("synthetic: rc-switch P1 x3", ra.encode_binary("100110100101", protocol=1) * 3),
        ("synthetic: tri-state P1 x3", ra.encode_tristate("0FF0F0FF0001", protocol=1) * 3),
        (
            "synthetic: Manchester x3 (8% jitter)",
            [
                v
                for seed in (1, 2, 3)
                for v in build_manchester("101100111000101101001101", 500, 0.08, seed)
            ],
        ),
    ] + stress_cases()


def stress_cases() -> list[tuple[str, list[int]]]:
    """Deliberately degraded copies of the held capture."""
    rng = random.Random(7)
    held = ra.trim_partial_frames(ra.normalize(HELD_CAPTURE))
    frames = ra.split_frames(held)
    # 1) one frame with a flipped PWM bit (swap its mark/space lengths)
    flipped = [list(f) for f in frames]
    flipped[2][10], flipped[2][11] = -flipped[2][11], -flipped[2][10]
    # 2) heavy timing jitter on every pulse (+-20%)
    jittered = [round(v * (1 + rng.uniform(-0.2, 0.2))) for v in held]
    # 3) a short glitch spike in the middle of a frame
    glitched = list(held)
    glitched[30:31] = [glitched[30], -40, 40]
    return [
        ("stress: one frame with a bit error", [v for f in flipped for v in f]),
        ("stress: +-20% jitter", jittered),
        ("stress: 40us glitch inside a frame", glitched),
        ("stress: single frame only", frames[3]),
    ]
